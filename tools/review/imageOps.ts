/**
 * Small picture-making helpers for the review boards: paste, fill, scale to
 * fit, and a tiny pixel font for labels. No dependencies.
 */
import { blankImage, type RgbaImage } from '../art/png';

export type Colour = [number, number, number, number?];

export function fill(img: RgbaImage, x: number, y: number, w: number, h: number, [r, g, b, a = 255]: Colour): void {
  const x0 = Math.max(0, Math.floor(x));
  const y0 = Math.max(0, Math.floor(y));
  const x1 = Math.min(img.width, Math.floor(x + w));
  const y1 = Math.min(img.height, Math.floor(y + h));
  for (let yy = y0; yy < y1; yy++) {
    for (let xx = x0; xx < x1; xx++) {
      const i = (yy * img.width + xx) * 4;
      img.data[i] = r;
      img.data[i + 1] = g;
      img.data[i + 2] = b;
      img.data[i + 3] = a;
    }
  }
}

/** Paste `src` into `dst` with its top-left at (x, y), blending see-through pixels over what's there. */
export function blit(dst: RgbaImage, src: RgbaImage, x: number, y: number): void {
  for (let sy = 0; sy < src.height; sy++) {
    const dy = y + sy;
    if (dy < 0 || dy >= dst.height) continue;
    for (let sx = 0; sx < src.width; sx++) {
      const dx = x + sx;
      if (dx < 0 || dx >= dst.width) continue;
      const s = (sy * src.width + sx) * 4;
      const d = (dy * dst.width + dx) * 4;
      const a = src.data[s + 3] / 255;
      for (let k = 0; k < 3; k++) dst.data[d + k] = Math.round(src.data[s + k] * a + dst.data[d + k] * (1 - a));
      dst.data[d + 3] = 255;
    }
  }
}

/**
 * Scale a picture to fit inside w x h, keeping its shape (centred, the rest
 * dark). Shrinking averages pixels (so concept art stays smooth); growing by a
 * whole number keeps pixels square.
 */
export function scaleToFit(src: RgbaImage, w: number, h: number, background: Colour = [24, 26, 32]): RgbaImage {
  const out = blankImage(w, h);
  fill(out, 0, 0, w, h, background);
  const scale = Math.min(w / src.width, h / src.height);
  const sw = Math.max(1, Math.round(src.width * scale));
  const sh = Math.max(1, Math.round(src.height * scale));
  const ox = Math.floor((w - sw) / 2);
  const oy = Math.floor((h - sh) / 2);
  const scaled = blankImage(sw, sh);
  for (let y = 0; y < sh; y++) {
    const fy0 = (y / sh) * src.height;
    const fy1 = ((y + 1) / sh) * src.height;
    for (let x = 0; x < sw; x++) {
      const fx0 = (x / sw) * src.width;
      const fx1 = ((x + 1) / sw) * src.width;
      const acc = [0, 0, 0, 0];
      let n = 0;
      // Average every source pixel the target pixel covers (at least one).
      for (let sy = Math.floor(fy0); sy < Math.max(Math.floor(fy0) + 1, Math.ceil(fy1)); sy++) {
        for (let sx = Math.floor(fx0); sx < Math.max(Math.floor(fx0) + 1, Math.ceil(fx1)); sx++) {
          const i = (Math.min(sy, src.height - 1) * src.width + Math.min(sx, src.width - 1)) * 4;
          for (let k = 0; k < 4; k++) acc[k] += src.data[i + k];
          n++;
        }
      }
      const o = (y * sw + x) * 4;
      for (let k = 0; k < 4; k++) scaled.data[o + k] = Math.round(acc[k] / n);
    }
  }
  blit(out, scaled, ox, oy);
  return out;
}


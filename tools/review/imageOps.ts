/** Width in pixels of `text` at `scale`. */
export const textWidth = (text: string, scale = 2): number => text.length * 6 * scale - scale;

/** Write `text` (capitals, digits, simple punctuation) with its top-left at (x, y). */
export function drawText(img: RgbaImage, x: number, y: number, text: string, colour: Colour = [255, 255, 255], scale = 2): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] ?? GLYPHS['?'];
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < 5; gx++) if (row & (1 << (4 - gx))) fill(img, cx + gx * scale, y + gy * scale, scale, scale, colour);
    });
    cx += 6 * scale;
  }
}
